/** Freeze browser source before bundling; runtime Function.toString can capture esbuild helpers. */
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const sourceFile=new URL('../src/admin/test-mode.mjs',import.meta.url);
const outputFile=new URL('../src/admin/test-mode-client-source.mjs',import.meta.url);
const source=(await readFile(sourceFile,'utf8')).replace(/\r\n?/g,'\n').replace(/^export (?=(?:async )?function )/gm,'');
if (/^\s*(?:import|export)\b/m.test(source))throw Error('Browser helpers must remain self-contained function declarations.');
const generated='/** Generated by scripts/generate-admin-test-mode.mjs; do not edit. */\nexport const TEST_MODE_CLIENT_SOURCE = '+JSON.stringify(source)+';\n';
if(process.argv.includes('--check')){
  if((await readFile(outputFile,'utf8')).replace(/\r\n?/g,'\n')!==generated)throw Error('Test mode browser source is stale. Run node scripts/generate-admin-test-mode.mjs.');
  console.log('Test mode browser source: current');
}else{
  await writeFile(outputFile,generated);
  console.log('Generated '+fileURLToPath(outputFile));
}
